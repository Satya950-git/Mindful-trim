const MOOD_LABELS: Record<number, string> = {
  1: 'Low',
  2: 'Down',
  3: 'Okay',
  4: 'Good',
  5: 'Great',
};

export function getCompletionMessage(mood: number, tags: string[], language = 'en'): string {
  const messages = language === 'hi' ? MESSAGES_HI : MESSAGES;
  const feeling = MOOD_LABELS[mood] ?? 'Okay';
  const s1 = tags[0] ?? '';
  const s2 = tags[1] ?? '';

  if (s1 && s2) {
    const key1 = `${feeling}|${s1}|${s2}`;
    if (messages[key1]) return messages[key1];
    const key2 = `${feeling}|${s2}|${s1}`;
    if (messages[key2]) return messages[key2];
  }

  if (s1) {
    const key = `${feeling}|${s1}|None`;
    if (messages[key]) return messages[key];
  }
  if (s2) {
    const key = `${feeling}|${s2}|None`;
    if (messages[key]) return messages[key];
  }

  return '';
}
